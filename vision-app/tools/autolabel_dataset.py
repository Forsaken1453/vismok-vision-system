# -*- coding: utf-8 -*-
"""Auto-label dataset ikan + siapkan struktur training YOLO.

Alur:
1. Buka semua foto di datasets\\<kelas>\\
2. YOLO-World (open-vocabulary) mendeteksi kotak "fish" di tiap foto
   -> label YOLO otomatis dgn class_id sesuai folder kelasnya
3. Foto TANPA deteksi ikan dibuang (jaga kualitas dataset)
4. Split 90/10 train/valid -> datasets\\export\\ + data.yaml

Pakai:  python tools\\autolabel_dataset.py [--conf 0.30]
"""
import argparse
import os
import random
import shutil
import sys

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DS = os.path.join(BASE, "datasets")
EXPORT = os.path.join(DS, "export")
EXPORT_YAML_PATH = EXPORT          # ditulis absolut: ultralytics me-resolve
                                   # 'path' terhadap datasets_dir global,
                                   # bukan folder yaml

# urutan kelas = urutan resmi aplikasi (harus konsisten dgn classes.json)
CLASS_ORDER = ["guppy", "koi", "cupang", "molly",
               "komet", "chana", "arwana", "ikan_mas"]

IMG_EXT = (".jpg", ".jpeg", ".png")


def build_model(conf):
    from ultralytics import YOLO
    print("memuat YOLO-World (unduh otomatis saat pertama kali)...")
    m = YOLO("yolov8s-worldv2.pt")       # open-vocabulary, ~150 MB
    m.set_classes(["fish"])
    print("model siap (classes = fish)")
    return m


def predict_boxes(m, img_path, conf):
    """Return list [(x1,y1,x2,y2,conf)] koordinat normalisasi YOLO."""
    r = m.predict(img_path, conf=conf, verbose=False, device=0)[0]
    if r.boxes is None or len(r.boxes) == 0:
        return []
    h, w = r.orig_shape
    out = []
    for b in r.boxes:
        x1, y1, x2, y2 = b.xyxyn[0].tolist()
        c = float(b.conf[0])
        # buang kotak yang terlalu kecil (< 4% area) — tidak berguna
        if (x2 - x1) * (y2 - y1) < 0.04:
            continue
        out.append((x1, y1, x2, y2, c))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--conf", type=float, default=0.30)
    ap.add_argument("--device", default="0")
    args = ap.parse_args()

    # kumpulkan (img_path, class_id)
    jobs = []
    for ci, cls in enumerate(CLASS_ORDER):
        d = os.path.join(DS, cls)
        if not os.path.isdir(d):
            print(f"!! folder kosong: {d}")
            continue
        for fn in sorted(os.listdir(d)):
            if fn.lower().endswith(IMG_EXT):
                jobs.append((os.path.join(d, fn), ci))
    print(f"total foto: {len(jobs)}")
    if not jobs:
        sys.exit("tidak ada foto - jalankan collect_dataset.py dulu")

    m = build_model(args.conf)

    labeled, skipped = [], []
    for i, (img, ci) in enumerate(jobs, 1):
        boxes = predict_boxes(m, img, args.conf)
        if boxes:
            labeled.append((img, ci, boxes))
        else:
            skipped.append(img)
        if i % 100 == 0:
            print(f"  {i}/{len(jobs)}  (label: {len(labeled)}, "
                  f"buang: {len(skipped)})")
    print(f"selesai: {len(labeled)} berlabel, {len(skipped)} dibuang "
          f"(tanpa ikan)")

    # ---------- susun struktur export ----------
    if os.path.isdir(EXPORT):
        shutil.rmtree(EXPORT)
    for sub in ("images/train", "images/valid",
                "labels/train", "labels/valid"):
        os.makedirs(os.path.join(EXPORT, sub), exist_ok=True)

    random.seed(2026)
    random.shuffle(labeled)
    n_val = max(1, int(len(labeled) * 0.10))
    split = {}
    for idx, (img, ci, boxes) in enumerate(labeled):
        part = "valid" if idx < n_val else "train"
        cls = CLASS_ORDER[ci]
        base = f"{cls}_{idx:05d}"
        shutil.copy(img, os.path.join(EXPORT, "images", part, base + ".jpg"))
        lines = []
        for (x1, y1, x2, y2, c) in boxes:
            xc, yc = (x1 + x2) / 2, (y1 + y2) / 2
            bw, bh = x2 - x1, y2 - y1
            lines.append(f"{ci} {xc:.6f} {yc:.6f} {bw:.6f} {bh:.6f}")
        with open(os.path.join(EXPORT, "labels", part, base + ".txt"),
                  "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        split[part] = split.get(part, 0) + 1
    print("split:", split)

    names_block = "\n".join(f"  {i}: {c}" for i, c in enumerate(CLASS_ORDER))
    yaml_text = (
        "# auto-generated by autolabel_dataset.py\n"
        f"path: {EXPORT_YAML_PATH}\n"
        "train: images/train\n"
        "val: images/valid\n"
        "names:\n" + names_block + "\n")
    with open(os.path.join(EXPORT, "data.yaml"), "w", encoding="utf-8") as f:
        f.write(yaml_text)
    print("data.yaml ditulis ->", EXPORT)
    print("LANJUT: python tools\\train_leviathan.py")


if __name__ == "__main__":
    main()
